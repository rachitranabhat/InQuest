"""Train the EXPERIMENTAL supervised model on synthetic labels.

The labels come from the synthetic generator (which customers had a suspicious
scenario injected). Because the data is synthetic and the scenarios are
generated by known rules, metrics here are optimistic and say nothing about
real-world performance. The model is not production-ready.

We also evaluate the rule-based prototype score on the same held-out customers
so the two approaches can be compared fairly.
"""
from __future__ import annotations

import json

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import confusion_matrix, f1_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import train_test_split

import config
from detection.feature_engineering import ML_FEATURES, ml_matrix

MODEL_PATH = config.ML_ARTIFACT_DIR / "random_forest.joblib"
METRICS_PATH = config.ML_ARTIFACT_DIR / "metrics.json"


def _metrics(y_true, y_pred, y_score=None) -> dict:
    out = {
        "precision": round(float(precision_score(y_true, y_pred, zero_division=0)), 3),
        "recall": round(float(recall_score(y_true, y_pred, zero_division=0)), 3),
        "f1": round(float(f1_score(y_true, y_pred, zero_division=0)), 3),
        "confusion_matrix": confusion_matrix(y_true, y_pred, labels=[0, 1]).tolist(),
    }
    if y_score is not None and len(set(y_true)) > 1:
        out["roc_auc"] = round(float(roc_auc_score(y_true, y_score)), 3)
    return out


def train(feats: pd.DataFrame, labels: pd.DataFrame, seed: int = config.RANDOM_SEED) -> dict:
    df = feats.merge(labels[["customer_id", "label_suspicious", "profile"]], on="customer_id")
    X = ml_matrix(df)
    y = df.label_suspicious.astype(int).to_numpy()

    idx_train, idx_test = train_test_split(
        np.arange(len(df)), test_size=0.3, stratify=y, random_state=seed
    )
    model = RandomForestClassifier(
        n_estimators=300, max_depth=6, min_samples_leaf=3, class_weight="balanced", random_state=seed
    )
    model.fit(X.iloc[idx_train], y[idx_train])

    proba = model.predict_proba(X.iloc[idx_test])[:, 1]
    pred = (proba >= 0.5).astype(int)
    rule_score = df.risk_score.to_numpy()[idx_test]
    rule_pred = (rule_score >= 30).astype(int)  # Medium or above

    importances = sorted(
        zip(ML_FEATURES, model.feature_importances_.round(4).tolist()), key=lambda t: t[1], reverse=True
    )
    metrics = {
        "model": "RandomForestClassifier (n_estimators=300, max_depth=6, class_weight=balanced)",
        "n_train": int(len(idx_train)),
        "n_test": int(len(idx_test)),
        "positive_rate": round(float(y.mean()), 3),
        "random_forest": _metrics(y[idx_test], pred, proba),
        "rule_based_score_ge_30": _metrics(y[idx_test], rule_pred, rule_score),
        "feature_importances": importances,
        "test_profiles": df.profile.iloc[idx_test].value_counts().to_dict(),
        "note": "Synthetic labels; metrics are optimistic and not indicative of real-world performance.",
    }

    config.ML_ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, MODEL_PATH)
    METRICS_PATH.write_text(json.dumps(metrics, indent=2))
    return metrics


if __name__ == "__main__":  # python -m ml.train  (requires pipeline outputs)
    from detection.anomaly_detection import run_detection

    tx = pd.read_csv(config.TRANSACTIONS_CSV)
    labels = pd.read_csv(config.CUSTOMERS_CSV)
    feats, _ = run_detection(tx)
    print(json.dumps(train(feats, labels), indent=2))
